  TO service_role
  USING (true);

CREATE POLICY "Service role only - keys insert"
  ON boost_keys FOR INSERT
  TO service_role
  WITH CHECK (true);

CREATE POLICY "Service role only - keys update"
  ON boost_keys FOR UPDATE
  TO service_role
  USING (true)
  WITH CHECK (true);

CREATE POLICY "Service role only - keys delete"
  ON boost_keys FOR DELETE
  TO service_role
