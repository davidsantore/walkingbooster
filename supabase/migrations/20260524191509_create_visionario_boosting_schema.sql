CREATE TABLE IF NOT EXISTS boost_tasks (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  key_id uuid REFERENCES boost_keys(id),
  guild_id text DEFAULT '',
  guild_name text DEFAULT '',
  guild_icon text DEFAULT '',
  invite_code text DEFAULT '',
  status text DEFAULT 'pending',
  stats jsonb DEFAULT '{"total":0,"joined":0,"boosted":0,"failed":0,"total_boosts":0}'::jsonb,
  tokens_detail jsonb DEFAULT '[]'::jsonb,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

